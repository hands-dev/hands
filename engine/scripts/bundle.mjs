#!/usr/bin/env node
/**
 * Build the committed plugin bundles: engine/src/{server,cli}.ts →
 * plugin/dist/{server,cli}-impl.mjs (esbuild, deps inlined, node builtins
 * external) plus tiny hand-authored wrapper entries that gate on the Node
 * floor BEFORE anything touches `node:sqlite` (a static import would hoist
 * past any in-module check; the wrapper's dynamic import cannot); engine/src/
 * books-server.ts → plugin/dist/books-server.mjs (no wrapper — it never
 * touches node:sqlite, so there's no floor to gate); plus the dashboard SPA:
 * engine/dashboard/ → plugin/dist/assets/dashboard.{js,css} (esbuild browser
 * bundle + the Tailwind v4 CLI).
 *
 * Run via `npm run bundle`. The bundles are committed — a plugin install is a
 * plain copy with no npm step — and __tests__/bundle.test.ts fails when they
 * go stale relative to src/. Determinism matters (the test byte-compares):
 * frontend deps are exact-pinned and styles.css uses `source(none)` so
 * Tailwind never scans machine-dependent paths.
 *
 * BUILD.json (commit + build time, for `hands version`/skew detection) is
 * deliberately NOT written here — see writeStamp() below. A plain `npm run
 * bundle` never touches it, on purpose: it's a per-commit stamp, so any two
 * branches' own local rebuilds always disagree on it, and if every dev/station
 * bundle run rewrote it, EVERY branch would carry a spurious BUILD.json diff
 * that conflicts with every other branch's on rebase (hands#166) — for a
 * field bundle.test.ts already excludes from its freshness check because it's
 * expected to differ per build. `npm run bundle:stamp` (CI's bundle-plugin.yml
 * only, right after a real merge to main) is the one place that refreshes it,
 * so a feature branch's copy simply never diverges from what it forked from —
 * nothing to reconcile on rebase.
 */
import * as esbuild from "esbuild";
import { spawnSync } from "node:child_process";
import * as fs from "node:fs";
import { createRequire } from "node:module";
import * as path from "node:path";
import { fileURLToPath } from "node:url";

const pkgDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const defaultOut = path.resolve(pkgDir, "..", "plugin", "dist");

const NODE_FLOOR_CHECK = (impl, extra = "") => `// generated by engine/scripts/bundle.mjs — do not edit
const [maj, min] = process.versions.node.split(".").map(Number);
if (maj < 22 || (maj === 22 && (min ?? 0) < 5)) {
  console.error(
    \`hands: Node >= 22.5 is required (node:sqlite); found \${process.versions.node}. \` +
      "Install a current Node and make sure it is first on PATH for Claude Code.",
  );
  process.exit(1);
}
${extra}await import("./${impl}");
`;

/** Short HEAD at build time, for the build stamp. Null outside a repo (e.g. a tarball build). */
function gitShort() {
  const res = spawnSync("git", ["rev-parse", "--short", "HEAD"], {
    cwd: pkgDir,
    encoding: "utf8",
    stdio: ["ignore", "pipe", "ignore"],
  });
  const out = res.stdout?.trim();
  return res.status === 0 && out ? out : null;
}

export async function buildBundles(outDir = defaultOut) {
  fs.mkdirSync(outDir, { recursive: true });
  const shared = {
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node22",
    legalComments: "none",
    external: ["node:*"],
    logLevel: "silent",
  };
  await esbuild.build({
    ...shared,
    entryPoints: [path.join(pkgDir, "src", "server.ts")],
    outfile: path.join(outDir, "server-impl.mjs"),
  });
  await esbuild.build({
    ...shared,
    entryPoints: [path.join(pkgDir, "src", "cli.ts")],
    outfile: path.join(outDir, "cli-impl.mjs"),
  });
  // The books MCP server is a single-file bundle, no wrapper: it never
  // imports Store/node:sqlite, so it has no Node-floor gate to enforce
  // before import (see engine/src/books-server.ts).
  await esbuild.build({
    ...shared,
    entryPoints: [path.join(pkgDir, "src", "books-server.ts")],
    outfile: path.join(outDir, "books-server.mjs"),
  });
  // Wrappers: version gate, then hand off. The server wrapper is what argv[1]
  // points at, so it flags the impl to run main() (the impl's own
  // invoked-directly check can't match through a wrapper).
  fs.writeFileSync(
    path.join(outDir, "server.mjs"),
    NODE_FLOOR_CHECK("server-impl.mjs", 'process.env.HANDS_FORCE_MAIN = "1";\n'),
  );
  fs.writeFileSync(path.join(outDir, "cli.mjs"), NODE_FLOOR_CHECK("cli-impl.mjs"));

  // Dashboard SPA — browser JS via esbuild…
  fs.mkdirSync(path.join(outDir, "assets"), { recursive: true });
  await esbuild.build({
    bundle: true,
    entryPoints: [path.join(pkgDir, "dashboard", "main.tsx")],
    outfile: path.join(outDir, "assets", "dashboard.js"),
    alias: { "@": path.join(pkgDir, "dashboard") }, // vendored shadcn files import "@/lib/utils" verbatim
    platform: "browser",
    format: "esm",
    target: "es2022",
    jsx: "automatic",
    minify: true,
    define: { "process.env.NODE_ENV": '"production"' }, // strips React dev mode (~3x smaller)
    legalComments: "none",
    logLevel: "silent",
  });
  // …and CSS via the Tailwind v4 CLI (bin resolved from the package manifest,
  // so no reliance on node_modules/.bin shims).
  const req = createRequire(import.meta.url);
  const cliPkgPath = req.resolve("@tailwindcss/cli/package.json");
  const cliPkg = JSON.parse(fs.readFileSync(cliPkgPath, "utf8"));
  const bin = typeof cliPkg.bin === "string" ? cliPkg.bin : cliPkg.bin.tailwindcss;
  const tailwind = spawnSync(
    process.execPath,
    [
      path.join(path.dirname(cliPkgPath), bin),
      "--input", path.join(pkgDir, "dashboard", "styles.css"),
      "--output", path.join(outDir, "assets", "dashboard.css"),
      "--minify",
    ],
    { cwd: pkgDir, stdio: ["ignore", "ignore", "inherit"] },
  );
  if (tailwind.status !== 0) throw new Error("tailwind css build failed");

  // Self-hosted brand fonts (Archivo, JetBrains Mono) — vendored via @fontsource so the
  // dashboard never makes an external network call to render, same posture as everything
  // else it does. Only the latin subset + weights styles.css actually references; the
  // packages ship many more (italics, other scripts) this dashboard has no use for.
  const fontsDir = path.join(outDir, "assets", "fonts");
  fs.mkdirSync(fontsDir, { recursive: true });
  const fontFiles = [
    "@fontsource/archivo/files/archivo-latin-400-normal.woff2",
    "@fontsource/archivo/files/archivo-latin-500-normal.woff2",
    "@fontsource/archivo/files/archivo-latin-600-normal.woff2",
    "@fontsource/archivo/files/archivo-latin-700-normal.woff2",
    "@fontsource/jetbrains-mono/files/jetbrains-mono-latin-400-normal.woff2",
  ];
  for (const spec of fontFiles) {
    fs.copyFileSync(req.resolve(spec), path.join(fontsDir, path.basename(spec)));
  }

  // Brand favicons/manifest — committed source lives under plugin/brand/ (copied in from the
  // brand kit once; not regenerated by this script, just relayed to assets/ alongside the rest
  // of the committed, byte-stable bundle output).
  const brandDir = path.join(pkgDir, "..", "plugin", "brand");
  for (const name of fs.readdirSync(brandDir)) {
    fs.copyFileSync(path.join(brandDir, name), path.join(outDir, "assets", name));
  }

  return outDir;
}

/**
 * Stamp the build so `hands version` / `hands doctor` can say WHICH build is
 * running and flag skew between a standalone install and a plugin cache.
 * Without this, "that command doesn't exist" is indistinguishable from
 * "you're running a different vintage than the one you edited".
 *
 * Deliberately separate from buildBundles() — see the file header. Call this
 * only from a release build (CI's `npm run bundle:stamp`, right after a real
 * merge to main), never from a plain dev/station `npm run bundle`.
 */
export function writeStamp(outDir = defaultOut) {
  fs.writeFileSync(
    path.join(outDir, "BUILD.json"),
    `${JSON.stringify(
      {
        version: JSON.parse(fs.readFileSync(path.join(pkgDir, "package.json"), "utf8")).version,
        commit: gitShort(),
        builtAt: new Date().toISOString(),
      },
      null,
      2,
    )}\n`,
  );
}

if (process.argv[1] && import.meta.url.endsWith(path.basename(process.argv[1]))) {
  const out = await buildBundles();
  if (process.argv.includes("--stamp")) writeStamp(out);
  process.stdout.write(`bundled → ${out}\n`);
}
