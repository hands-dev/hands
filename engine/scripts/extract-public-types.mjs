#!/usr/bin/env node
/**
 * Extracts the public-snapshot type surface from engine/src/snapshot.ts as a
 * standalone .d.ts — the type-level half of the asset sync (see
 * engine/scripts/bundle.mjs for the JS/CSS half). hands-website vendors both
 * in the same sync PR instead of depending on a published package (decided:
 * no npm package for v1 — see plan #36's ticket 1).
 *
 * This is a lightweight source-text extraction, not a tsc declaration
 * build: buildPublicSnapshot()'s dependencies (Store, NodeJS.ProcessEnv)
 * would otherwise have to resolve across the whole module graph for a
 * two-repo audience that only needs 5 flat data interfaces. Internal
 * `Snapshot{Question,Task,Todo}` names are renamed to `Public{Question,Task,
 * Todo}` on the way out — they're structurally identical to what
 * hands-website's lib/dashboard.ts used to hand-duplicate under those names.
 */
import * as fs from "node:fs";
import * as path from "node:path";
import { fileURLToPath } from "node:url";
import { extractInterfaces } from "./extract-interfaces.mjs";

const pkgDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const defaultSource = path.join(pkgDir, "src", "snapshot.ts");

const RENAME = {
  SnapshotQuestionOption: "PublicQuestionOption",
  SnapshotQuestion: "PublicQuestion",
  SnapshotTask: "PublicTask",
  SnapshotTodo: "PublicTodo",
  SnapshotMenuItem: "PublicMenuItem",
};

// Declaration order in the emitted file: crafts, the option type SnapshotQuestion
// references, the renamed record types, then the snapshot shape that references
// all of them.
const INTERFACES = [
  "PublicCraft",
  "SnapshotQuestionOption",
  "SnapshotQuestion",
  "SnapshotTask",
  "SnapshotTodo",
  "SnapshotMenuItem",
  "PublicSnapshot",
];

export function extractPublicTypes(sourcePath = defaultSource) {
  const blocks = extractInterfaces(sourcePath, INTERFACES, RENAME);
  return `// generated by engine/scripts/extract-public-types.mjs from engine/src/snapshot.ts — do not edit by hand
// the redacted, remote-safe snapshot shape written to journal/<project>/<handle>/dashboard.json (see remote.ts syncPush)

${blocks.join("\n\n")}
`;
}

if (process.argv[1] && import.meta.url.endsWith(path.basename(process.argv[1]))) {
  const outPath = process.argv[2];
  const dts = extractPublicTypes();
  if (outPath) {
    fs.mkdirSync(path.dirname(outPath), { recursive: true });
    fs.writeFileSync(outPath, dts);
    process.stdout.write(`extracted → ${outPath}\n`);
  } else {
    process.stdout.write(dts);
  }
}
